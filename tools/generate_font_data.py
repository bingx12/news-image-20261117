#!/usr/bin/env python3
"""Render DejaVu Sans glyphs into a Python bitmap-font module.

Build-time only: needs Pillow, which the entry itself never imports.
The output (font_data.py) is committed with the entry; main.py reads it.

Each glyph is stored at 64 px as a greyscale bitmap plus its advance
and its offset from the pen position, so main.py can draw text at any
size by area-sampling the bitmap. Output is deterministic: fixed
character order, fixed fonts, no timestamps.
"""

import base64
import os

from PIL import Image, ImageDraw, ImageFont

SIZE = 64
REGULAR_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
BOLD_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"

# Printable ASCII plus the punctuation this entry's copy uses.
CHARS = "".join(chr(c) for c in range(32, 127))
CHARS += "\u2014\u2013\u2018\u2019\u201c\u201d\u2022\u00b0\u00d7\u2192\u2026\u20ac\u00a3\u00a7\u00b7"

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_PATH = os.path.join(HERE, "..", "font_data.py")


def render_glyph(font, ch):
    """Return (advance, width, height, dx, dy, base64 bitmap).

    dx/dy are the ink box's top-left corner relative to the pen
    position on the baseline, in 64 px units. The bitmap is greyscale
    (0 = transparent, 255 = full ink), row-major.
    """
    advance = font.getlength(ch)
    canvas = Image.new("L", (SIZE * 3, SIZE * 3), 0)
    draw = ImageDraw.Draw(canvas)
    base = SIZE  # baseline row inside the canvas
    draw.text((SIZE, base), ch, font=font, fill=255, anchor="ls")
    box = canvas.getbbox()
    if box is None:
        return (advance, 0, 0, 0, 0, "")
    x0, y0, x1, y1 = box
    crop = canvas.crop(box)
    raw = crop.tobytes()
    return (advance, x1 - x0, y1 - y0, x0 - SIZE, y0 - base,
            base64.b64encode(raw).decode("ascii"))


def main():
    fonts = {
        "regular": ImageFont.truetype(REGULAR_PATH, SIZE),
        "bold": ImageFont.truetype(BOLD_PATH, SIZE),
    }
    lines = []
    lines.append("# Bitmap font data: DejaVu Sans Book + Bold, rendered at 64 px.")
    lines.append("# Generated by tools/generate_font_data.py (Pillow, build-time only).")
    lines.append("# Deterministic: fixed fonts, fixed character order, no timestamps.")
    lines.append("")
    lines.append("SIZE = %d" % SIZE)
    lines.append("")
    lines.append("METRICS = {")
    for name in ("regular", "bold"):
        ascent, descent = fonts[name].getmetrics()
        lines.append("    %r: (%d, %d)," % (name, ascent, descent))
    lines.append("}")
    lines.append("")
    lines.append("# (advance, width, height, dx, dy, base64 greyscale bitmap).")
    lines.append("# dx/dy are relative to the pen on the baseline, in 64 px units.")
    lines.append("GLYPHS = {")
    for name in ("regular", "bold"):
        font = fonts[name]
        for ch in CHARS:
            adv, w, h, dx, dy, data = render_glyph(font, ch)
            lines.append("    (%r, %r): (%r, %d, %d, %d, %d, %r)," % (
                name, ch, adv, w, h, dx, dy, data))
    lines.append("}")
    lines.append("")
    text = "\n".join(lines)
    with open(OUT_PATH, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote %s (%d bytes, %d glyphs)" % (
        OUT_PATH, len(text.encode("utf-8")), len(CHARS) * 2))


if __name__ == "__main__":
    main()
